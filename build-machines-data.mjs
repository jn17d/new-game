// Regenerates machines-data.js from the Piskel conveyor export.
// Usage: node build-machines-data.mjs
// (mirrors fetch-buildings.mjs — keeps the game working from file://)
import { readFileSync, writeFileSync } from 'node:fs';

const SRC_PNG = 'pixel art/conveyor/conveyor.png';
const SRC_JSON = 'pixel art/conveyor/conveyor.json';
const OUT = 'machines-data.js';

const png = readFileSync(SRC_PNG);
const meta = JSON.parse(readFileSync(SRC_JSON, 'utf8'));

// Sort frames numerically ("New Piskel10.png" would sort before
// "New Piskel2.png" as plain strings — classic Piskel gotcha).
const frames = Object.keys(meta.frames)
  .map((name) => {
    const digits = name.match(/(\d+)\.png$/);
    return { n: digits ? parseInt(digits[1], 10) : 0, f: meta.frames[name].frame };
  })
  .sort((a, b) => a.n - b.n)
  .map(({ f }) => ({ x: f.x, y: f.y }));

// Measured from the sprite (2026-09 pixel probe):
// - content occupies x=5..26 (22px of 32), y=0..31
// - slats repeat every 5px vertically, each frame shifts them +2px downward
const TRIM = { x: 5, y: 0, w: 22, h: 32 };
const STRIPE_PERIOD = 5;
const FRAME_SHIFT = 2;

const out = `// AUTO-GENERATED by build-machines-data.mjs — do not edit by hand.
// Source: ${SRC_PNG} (Piskel export, ${meta.meta.size.w}x${meta.meta.size.h} sheet)
// Delivered as base64 so the game runs from file:// without a server.
window.MACHINE_ASSETS = {
  conveyor: {
    // The Piskel atlas JSON names the image "New Piskel.png", which does not
    // match the actual file — so we skip Pixi's spritesheet parser and build
    // frame textures directly from this embedded PNG (see index.html).
    image: "data:image/png;base64,${png.toString('base64')}",
    frames: ${JSON.stringify(frames)},
    frameWidth: ${frames.length ? meta.frames[Object.keys(meta.frames)[0]].frame.w : 32},
    frameHeight: ${frames.length ? meta.frames[Object.keys(meta.frames)[0]].frame.h : 32},
    trim: ${JSON.stringify(TRIM)},          // real content bounds inside each frame
    stripePeriod: ${STRIPE_PERIOD},          // px between slats
    frameShift: ${FRAME_SHIFT},              // px slats travel per frame (downward)
    // Future: a seamless cap-less strip tile here switches belt runs to
    // TilingSprites (one per row, animated via tilePosition) automatically.
    tile: null
  },
  // Future: a box/crate sprite for animated deliveries between buildings
  // (factory -> warehouse on production, storage -> NPC buyer on a sale).
  // Shape expected by index.html's BOX_VISUALS seam — drop it in and every
  // delivery swaps from the 📦 emoji to this sprite automatically:
  //   box: { image: "data:image/png;base64,..." }   // whole-frame sprite
  //   box: { image, frameWidth, frameHeight, frames: [{x,y}] }  // atlas form
  box: null
};
`;

writeFileSync(OUT, out);
console.log(`Wrote ${OUT}: ${frames.length} frames, ${png.length}-byte PNG inlined`);
